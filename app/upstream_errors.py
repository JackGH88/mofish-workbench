def http_status(value: object) -> int:
    try: number = int(str(value).strip())
    except (TypeError, ValueError): return 0
    return number if 100 <= number <= 599 else 0

def status_from_text(text: object) -> int:
    match = _STATUS_RE.search(str(text or ""))
    return http_status(match.group(1)) if match else 0

def failure_message(status: Optional[object] = None) -> str:
    resolved = http_status(status)
    return f"{GENERIC_FAILURE} HTTP {resolved}" if resolved else GENERIC_FAILURE

def exposes_provider(text: object) -> bool:
    value = str(text or "")
    return bool(_URL_RE.search(value) or any(word.lower() not in _SAFE_WORDS for word in re.findall(r"[a-zA-Z][a-zA-Z_-]*", value)))

def sanitize_message(message: object, *, status: Optional[object] = None) -> str:
    text = str(message or "").strip()
    return failure_message(http_status(status) or status_from_text(text)) if exposes_provider(text) else text

def public_code(code: object) -> str:
    text = str(code or "").strip()
    if not text: return ""
    return text if text in _PUBLIC_CODES else GENERIC_CODE

def public_error(code: object, message: object, *, status: Optional[object] = None) -> tuple[str, str]:
    return public_code(code), sanitize_message(message, status=status)

def public_details(raw: object) -> dict:
    if not isinstance(raw, Mapping): return {}
    output = {}
    for key, value in raw.items():
        if key in {"requiredPoints", "availablePoints", "frozenPoints", "chargedPoints", "maxChargePoints"}:
            if isinstance(value, (int, float, str)) and not isinstance(value, bool) and re.fullmatch(r"[0-9]{1,18}(?:\.[0-9]{1,6})?", str(value)):
                output[key] = value
        elif key in {"orderId", "taskId", "quoteId", "budgetId"}:
            if isinstance(value, str) and re.fullmatch(r"[A-Za-z0-9_-]{1,100}", value): output[key] = value
        elif key == "retryAfterSeconds":
            if isinstance(value, int) and not isinstance(value, bool) and 0 <= value <= 86400: output[key] = value
    return output
